static const uint8_t *lookup(char c){
    if(c>='a'&&c<='z')c=(char)(c-'a'+'A');
    for(size_t i=0;i<sizeof(font)/sizeof(font[0]);i++)
        if(font[i].c==c)return font[i].row;
    return font[sizeof(font)/sizeof(font[0])-1].row;
}
void gfx_text(int x,int y,const char *text,uint32_t color,int scale){
    if(scale<1)scale=1;
    while(*text){
        const uint8_t *rows=lookup(*text++);
        for(int r=0;r<7;r++)for(int c=0;c<5;c++)
            if(rows[r]&(1u<<(4-c)))
                gfx_rect(x+c*scale,y+r*scale,scale,scale,color);
        x+=6*scale;
        if(x>=gfx_width())return;
    }
}
